package com.expensetracker.data

enum class TxType {
    EXPENSE,
    INCOME,

    /**
     * Money moved between the user's own accounts. Deliberately excluded from
     * every income/expense total and category breakdown — it is not spending,
     * only a change of location — but it does move both account balances.
     */
    TRANSFER
}

enum class TxSource { MANUAL, SMS, RECURRING, IMPORT }

/** A category such as "Shopping - Personal" or "Salary". */
data class Category(
    val id: Long = 0,
    val name: String,
    val type: TxType,
    val emoji: String = "📁",
    val colorArgb: Int = 0xFF6B7280.toInt(),
    /** Monthly spending cap for this category; 0 means no budget set. */
    val budget: Double = 0.0,
    val archived: Boolean = false
)

/** What kind of payment detail a [PayTag] describes. */
enum class PayKind { MODE, METHOD, BANK }

/**
 * A user-extendable payment detail: how the money moved (mode), the instrument
 * (method), or which bank. Seeded with common values; the user can add their own.
 */
data class PayTag(
    val id: Long = 0,
    val kind: PayKind,
    val name: String,
    val archived: Boolean = false
)

/** A person an expense was made on / income received from. */
data class Person(
    val id: Long = 0,
    val name: String,
    val note: String = "",
    val archived: Boolean = false
)

/** Where money moved: Cash, HDFC Bank, Credit Card, UPI ... */
data class Account(
    val id: Long = 0,
    val name: String,
    val emoji: String = "🏦",
    val openingBalance: Double = 0.0,
    val archived: Boolean = false
)

data class Transaction(
    val id: Long = 0,
    val type: TxType,
    val amount: Double,
    val date: Long,
    val categoryId: Long?,
    val personId: Long?,
    val accountId: Long?,
    val merchant: String = "",
    val note: String = "",
    val source: TxSource = TxSource.MANUAL,
    /** Set when this row was generated by a [RecurringRule]. */
    val recurringId: Long? = null,
    /** Destination account for a [TxType.TRANSFER]; null otherwise. */
    val toAccountId: Long? = null,
    val modeId: Long? = null,
    val methodId: Long? = null,
    val bankId: Long? = null,
    val createdAt: Long = System.currentTimeMillis()
)

/** A transaction joined with its lookup names, for display. */
data class TxView(
    val tx: Transaction,
    val categoryName: String?,
    val categoryEmoji: String?,
    val categoryColor: Int?,
    val personName: String?,
    val accountName: String?,
    val accountEmoji: String?,
    /** Destination account name for a transfer. */
    val toAccountName: String? = null,
    val methodName: String? = null,
    val bankName: String? = null
)

/** An SMS the parser recognised but the user has not confirmed yet. */
data class PendingSms(
    val id: Long = 0,
    val sender: String,
    val body: String,
    val receivedAt: Long,
    val amount: Double,
    val type: TxType,
    val merchant: String,
    val accountHint: String,
    val refHash: String,
    val status: String = "PENDING" // PENDING | ACCEPTED | IGNORED
)

/** Aggregate row used by the report screens. */
data class Bucket(
    val key: String,
    val label: String,
    val amount: Double,
    val colorArgb: Int = 0,
    val emoji: String = "",
    val count: Int = 0
)

/** A category's budget alongside what has been spent against it this period. */
data class CategoryBudget(
    val category: Category,
    val spent: Double
) {
    val budget: Double get() = category.budget
    val remaining: Double get() = budget - spent
    val over: Boolean get() = spent > budget
    /** Share of the budget used; can exceed 1 when overspent. */
    val usedFraction: Float
        get() = if (budget <= 0) 0f else (spent / budget).toFloat()
    /** True once spending passes 80% but is still inside the budget. */
    val nearLimit: Boolean get() = !over && usedFraction >= 0.8f
}

data class Totals(val income: Double, val expense: Double) {
    val balance: Double get() = income - expense
}
